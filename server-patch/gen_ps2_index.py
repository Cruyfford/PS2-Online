"""يولّد server/ps2_index.js من ملف Redump (libretro-database: metadat/redump/Sony - PlayStation 2.dat)
السطر: SERIAL<TAB>اسم اللعبة — لأغلفة libretro-thumbnails (Sony - PlayStation 2)"""
import re, sys
src, out = sys.argv[1], sys.argv[2]
txt = open(src, encoding="utf-8").read()
rows, seen = [], set()
for m in re.finditer(r'game \(\s*name "([^"]+)"(.*?)\n\)', txt, re.S):
    name, body = m.group(1), m.group(2)
    s = re.search(r'^\s*serial "([^"]+)"', body, re.M)
    serials = re.split(r"[,\s]+", s.group(1).upper()) if s else [""]
    for ser in serials:
        key = (ser, name)
        if key in seen:
            continue
        seen.add(key)
        rows.append(f"{ser}\t{name}")
data = "\n".join(rows).replace("\\", "\\\\").replace("`", "\\`").replace("${", "\\${")
open(out, "w", encoding="utf-8").write("// generated by tools/gen_ps2_index.py — do not edit\nexport default `" + data + "`;\n")
print(len(rows), "rows")
